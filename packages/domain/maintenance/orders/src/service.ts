import { WorkOrderError } from './errors.js';
import {
  closureVehicleStatus,
  dateOnly,
  kilometers,
  opaqueId,
  optionalId,
  optionalText,
  record,
  text,
} from './rules.js';
import { parseCosts, parseWork } from './work.js';
import { WorkOrderServiceBase } from './base.js';
import { PREVENTIVE_ORDER_CLOSED_EVENT, type WorkOrder, type WorkOrderEvent } from './types.js';
import { missing, requireCommand, type WorkOrderActor } from './workflow.js';

export type { WorkOrderServiceOptions } from './base.js';

/** Workflow of SPECS §6.1 for preventive (MNT-PLANS) and corrective orders. */
export class WorkOrderService extends WorkOrderServiceBase {
  public async createCorrective(
    tenantId: string,
    actor: WorkOrderActor,
    input: unknown,
  ): Promise<WorkOrder> {
    if (!actor.permissions.includes('create')) throw new WorkOrderError('forbidden');
    const data = record(input, ['vehicleId', 'description']);
    const vehicleId = opaqueId(data['vehicleId']);
    const description = text(data['description'], 2000);
    if (!(await this.refs.vehicleExists(tenantId, vehicleId)))
      throw new WorkOrderError('not_found');
    const order = this.blank(actor, tenantId, {
      id: this.newId(),
      kind: 'corrective',
      vehicleId,
      planId: null,
      occurrenceId: null,
      description,
      workshopId: null,
      mechanicId: null,
    });
    return this.insert(actor, order);
  }

  /** Opens the work order of a scheduled order generated by MNT-PLANS; it keeps that order's id. */
  public async adoptPreventive(
    tenantId: string,
    actor: WorkOrderActor,
    input: unknown,
  ): Promise<WorkOrder> {
    if (!actor.permissions.includes('create')) throw new WorkOrderError('forbidden');
    const data = record(input, ['planId', 'scheduledOrderId']);
    const planId = opaqueId(data['planId']);
    const orderId = opaqueId(data['scheduledOrderId']);
    const scheduled = await this.refs.scheduledOrder(tenantId, planId, orderId);
    if (!scheduled) throw new WorkOrderError('not_found');
    if (scheduled.status !== 'scheduled') throw new WorkOrderError('invalid_transition');
    if (await this.store.get(tenantId, scheduled.id)) throw new WorkOrderError('duplicate');
    const order = this.blank(actor, tenantId, {
      id: scheduled.id,
      kind: 'preventive',
      vehicleId: scheduled.vehicleId,
      planId: scheduled.planId,
      occurrenceId: scheduled.occurrenceId,
      description: null,
      workshopId: scheduled.workshopId,
      mechanicId: scheduled.mechanicId,
    });
    return this.insert(actor, order);
  }

  public async assign(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const data = record(input, [
      'version',
      'responsibleId',
      'workshopId',
      'mechanicId',
      'scheduledDate',
    ]);
    const order = await this.prepare(tenantId, actor, id, 'assign', data['version']);
    const responsibleId = optionalId(data['responsibleId']);
    const workshopId =
      data['workshopId'] === undefined ? order.workshopId : optionalId(data['workshopId']);
    const mechanicId =
      data['mechanicId'] === undefined ? order.mechanicId : optionalId(data['mechanicId']);
    const scheduledDate =
      data['scheduledDate'] === undefined || data['scheduledDate'] === null
        ? null
        : dateOnly(data['scheduledDate']);
    missing({
      responsibleId: responsibleId !== null,
      scheduledDate: scheduledDate !== null,
      workshopOrMechanic: workshopId !== null || mechanicId !== null,
    });
    if (!(await this.refs.isTenantMember(tenantId, responsibleId as string)))
      throw new WorkOrderError('invalid_association');
    const workshop = workshopId ? await this.refs.workshop(tenantId, workshopId) : null;
    const mechanic = mechanicId ? await this.refs.mechanic(tenantId, mechanicId) : null;
    if ((workshopId && !workshop?.active) || (mechanicId && !mechanic?.active))
      throw new WorkOrderError('invalid_association');
    if (
      mechanic &&
      workshopId &&
      mechanic.workshopId !== null &&
      mechanic.workshopId !== workshopId
    )
      throw new WorkOrderError('invalid_association');
    return this.transition(
      order,
      actor,
      'assign',
      { responsibleId, workshopId, mechanicId, scheduledDate },
      null,
    );
  }

  public async start(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const data = record(input, ['version', 'requiresWorkshop']);
    const order = await this.prepare(tenantId, actor, id, 'start', data['version']);
    const requiresWorkshop =
      data['requiresWorkshop'] === undefined ? order.workshopId !== null : data['requiresWorkshop'];
    if (typeof requiresWorkshop !== 'boolean') throw new WorkOrderError('invalid_input');
    return this.transition(
      order,
      actor,
      'start',
      { requiresWorkshop, startedAt: this.now().toISOString() },
      null,
    );
  }

  public async complete(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const data = record(input, ['version', 'actualDate', 'actualKm']);
    const order = await this.prepare(tenantId, actor, id, 'complete', data['version']);
    const actualDate = data['actualDate'] === undefined ? null : dateOnly(data['actualDate']);
    const actualKm = data['actualKm'] === undefined ? null : kilometers(data['actualKm']);
    missing({
      actualDate: actualDate !== null,
      actualKm: actualKm !== null,
      tasks: order.tasks.length > 0,
    });
    const today = this.now().toISOString().slice(0, 10);
    if ((actualDate as string) > today) throw new WorkOrderError('invalid_input');
    if (order.kind === 'preventive' && order.planId) {
      const baseline = await this.refs.planBaseline(tenantId, order.planId);
      if (!baseline) throw new WorkOrderError('not_found');
      // A closure before the plan's last service would move the next target backwards.
      if (baseline.lastServiceDate !== null && (actualDate as string) < baseline.lastServiceDate)
        throw new WorkOrderError('invalid_input');
      if (baseline.lastServiceKm !== null && (actualKm as number) < baseline.lastServiceKm)
        throw new WorkOrderError('invalid_input');
    }
    return this.transition(
      order,
      actor,
      'complete',
      { actualDate, actualKm, completedAt: this.now().toISOString() },
      null,
    );
  }

  public async approveClose(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const data = record(input, ['version']);
    const order = await this.prepare(tenantId, actor, id, 'approve_close', data['version']);
    if (!(await this.refs.closeApprovalRequired(tenantId)))
      throw new WorkOrderError('invalid_transition');
    if (order.closeApproval) throw new WorkOrderError('duplicate');
    const closeApproval = { approvedBy: actor.id, approvedAt: this.now().toISOString() };
    return this.transition(order, actor, 'approve_close', { closeApproval }, null);
  }

  public async close(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const data = record(input, ['version', 'vehicleStatus', 'comment']);
    const order = await this.prepare(tenantId, actor, id, 'close', data['version']);
    const vehicleStatus =
      data['vehicleStatus'] === undefined ? null : closureVehicleStatus(data['vehicleStatus']);
    const comment = optionalText(data['comment'], 1000);
    const approvalRequired = await this.refs.closeApprovalRequired(tenantId);
    missing({
      vehicleStatus: vehicleStatus !== null,
      closeApproval: !approvalRequired || order.closeApproval !== null,
    });
    if (vehicleStatus === 'active') {
      const others = (await this.store.openWorkshopOrders(tenantId, order.vehicleId)).filter(
        (other) => other.id !== order.id,
      );
      // Returning to active never ignores another open workshop episode (SPECS §5.3).
      missing({ noOtherOpenWorkshopOrders: others.length === 0 });
    }
    const closedAt = this.now().toISOString();
    const extra: WorkOrderEvent[] =
      order.kind === 'preventive' && order.planId && order.occurrenceId
        ? [
            {
              type: PREVENTIVE_ORDER_CLOSED_EVENT,
              payload: {
                planId: order.planId,
                occurrenceId: order.occurrenceId,
                orderId: order.id,
                kind: 'preventive',
                completedAt: order.completedAt as string,
                actualDate: order.actualDate as string,
                actualKm: order.actualKm as number,
              },
            },
          ]
        : [];
    return this.transition(
      order,
      actor,
      'close',
      { closedAt, closedBy: actor.id, vehicleStatusDecision: vehicleStatus },
      comment,
      extra,
    );
  }

  public async cancel(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const data = record(input, ['version', 'reason']);
    const order = await this.prepare(tenantId, actor, id, 'cancel', data['version']);
    const reason = data['reason'] === undefined ? null : text(data['reason'], 1000);
    missing({ reason: reason !== null });
    return this.transition(order, actor, 'cancel', { cancelReason: reason }, reason);
  }

  public async reopen(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const data = record(input, ['version', 'reason']);
    const order = await this.prepare(tenantId, actor, id, 'reopen', data['version']);
    const reason = data['reason'] === undefined ? null : text(data['reason'], 1000);
    missing({ reason: reason !== null });
    const cleared = {
      closeApproval: null,
      closedAt: null,
      closedBy: null,
      vehicleStatusDecision: null,
      completedAt: null,
      reopenCount: order.reopenCount + 1,
    };
    return this.transition(order, actor, 'reopen', cleared, reason);
  }

  public async updateWork(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const order = await this.get(tenantId, actor, id);
    requireCommand(actor, 'work', order);
    const parsed = parseWork(input, order, this.newId);
    return this.edit(
      order,
      actor,
      parsed.version,
      parsed.changes,
      'maintenance.work_order.work_recorded',
    );
  }

  public async updateCosts(
    tenantId: string,
    actor: WorkOrderActor,
    id: string,
    input: unknown,
  ): Promise<WorkOrder> {
    const order = await this.get(tenantId, actor, id);
    requireCommand(actor, 'costs', order);
    const parsed = parseCosts(input, order, this.newId);
    return this.edit(
      order,
      actor,
      parsed.version,
      parsed.changes,
      'maintenance.work_order.costs_recorded',
    );
  }
}
